// Desafio 07 - Verificador de número positivo ou negativo

console.log("Bem vindo ao Verificador de Número Positivo ou Negativo \n");

//Realidade 1: Número positivo

numero = 10;

if (numero > 0) {
  console.log(`O número ${numero} é positivo!`);
} else {
  console.log(`O número ${numero} é negativo!`);
}

//Realidade 2: Número negativo

numero = -5;

if (numero > 0) {
  console.log(`O número ${numero} é positivo!`);
} else {
  console.log(`O número ${numero} é negativo!`);
}
